"""Track C transit survey: one shard on a Kaggle CPU session.

Generated by build_kernel.py from kernel_template.py; the payload lines below are filled in.
Steps: report the session's resources; get the code at a pinned commit (git clone of the
public repo, or an embedded `git archive` of that commit); build a Python 3.13 venv with the
gate-2 package pins (uv); run run_survey.py on this shard with a wall-clock guard; delete the
light curves; pack the result records into /kaggle/working/<shard>.tar.gz.
Logs show progress counts only (blinding): the runner never prints signals.
"""

import base64
import gzip
import json
import os
import shutil
import subprocess
import sys
import tarfile
import time

T0 = time.time()
CFG = json.loads(base64.b64decode("@@CFG@@").decode())
TARGETS_GZ = "@@TARGETS@@"
SKIP_GZ = "@@SKIP@@"
CODE_TGZ = "@@CODE@@"

W = "/kaggle/working"
ROOT = f"{W}/ow"  # ODDBALL_MAIN: outputs/ and data/ go under it
CODE = "/tmp/ow-code"
VENV = "/tmp/ow-venv"
SHARD = f"shard{CFG['shard']:03d}of{CFG['of']:03d}"


def sh(cmd, **kw):
    print("$", " ".join(cmd), flush=True)
    return subprocess.run(cmd, check=True, **kw)


def report_resources():
    mem = open("/proc/meminfo").read().split("\n")[0]
    du = shutil.disk_usage(W)
    print(f"resources: cpus {os.cpu_count()} affinity {len(os.sched_getaffinity(0))} {mem} "
          f"working free {du.free / 1e9:.1f} GB  python {sys.version.split()[0]}", flush=True)
    try:
        cg = open("/sys/fs/cgroup/cpu.max").read().strip()
        print(f"cgroup cpu.max {cg}", flush=True)
    except OSError:
        pass


def get_code():
    if CODE_TGZ:
        os.makedirs(CODE, exist_ok=True)
        with tarfile.open(fileobj=__import__("io").BytesIO(base64.b64decode(CODE_TGZ))) as t:
            t.extractall(CODE, filter="data")
        print(f"code: embedded git archive of {CFG['commit']}", flush=True)
        return
    sh(["git", "clone", "--quiet", "--filter=blob:none", "--no-checkout", CFG["repo"], CODE])
    sh(["git", "-C", CODE, "checkout", "--quiet", CFG["commit"]])
    head = subprocess.run(["git", "-C", CODE, "rev-parse", "HEAD"], capture_output=True,
                          text=True, check=True).stdout.strip()
    if head != CFG["commit"]:
        raise SystemExit(f"checked out {head}, wanted {CFG['commit']}")
    print(f"code: git {CFG['repo']} at {head}", flush=True)


def make_venv() -> str:
    sh([sys.executable, "-m", "pip", "install", "--quiet", "--disable-pip-version-check",
        f"uv=={CFG['uv']}"])
    uv = [sys.executable, "-m", "uv"]
    sh(uv + ["venv", "--quiet", "--python", CFG["python"], VENV])
    py = f"{VENV}/bin/python"
    sh(uv + ["pip", "install", "--quiet", "--python", py] + CFG["pins"])
    return py


def main():
    report_resources()
    get_code()
    py = make_venv()
    tg = "/tmp/targets.csv"
    with open(tg, "wb") as fh:
        fh.write(gzip.decompress(base64.b64decode(TARGETS_GZ)))
    args = ["--tag", CFG["tag"], "--targets", tg, "--min-sectors", str(CFG["min_sectors"]),
            "--shard", str(CFG["shard"]), "--of", str(CFG["of"]), "--procs", str(CFG["procs"]),
            "--route", CFG["route"], "--grace-min", str(CFG["grace_min"])]
    if SKIP_GZ:
        with open("/tmp/skip.txt", "wb") as fh:
            fh.write(gzip.decompress(base64.b64decode(SKIP_GZ)))
        args += ["--skip-tics", "/tmp/skip.txt"]
    # the guard counts from the runner's start, so subtract the setup time already spent
    hours = CFG["budget_hours"] - (time.time() - T0) / 3600
    args += ["--max-hours", f"{hours:.3f}"]
    env = dict(os.environ, ODDBALL_MAIN=ROOT, CUDA_VISIBLE_DEVICES="", PYTHONUNBUFFERED="1",
               NUMBA_NUM_THREADS="1", OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1",
               MKL_NUM_THREADS="1")
    out = f"{ROOT}/outputs/planets_spike/{CFG['tag']}"
    sd = f"{out}/shards/{SHARD}" if CFG["of"] > 1 else out
    os.makedirs(sd, exist_ok=True)
    runner = f"{CODE}/spikes/mdwarf_stack/survey/run_survey.py"
    with open(f"{sd}/survey.log", "a") as log:
        p = subprocess.Popen([py, "-I", runner] + args, env=env, cwd=CODE,
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        for line in p.stdout:
            sys.stdout.write(line)
            log.write(line)
        rc = p.wait()
    print(f"runner exit {rc} after {(time.time() - T0) / 3600:.2f} h", flush=True)
    shutil.rmtree(f"{ROOT}/data", ignore_errors=True)  # results only leave Kaggle
    n = len(os.listdir(f"{sd}/results")) if os.path.isdir(f"{sd}/results") else 0
    summary = {"shard": CFG["shard"], "of": CFG["of"], "commit": CFG["commit"],
               "runner_exit": rc, "n_results": n, "hours": (time.time() - T0) / 3600}
    with open(f"{sd}/kaggle_summary.json", "w") as fh:
        json.dump(summary, fh)
    tgz = f"{W}/{CFG['tag']}_{SHARD}.tar.gz"
    with tarfile.open(tgz, "w:gz") as t:
        t.add(f"{ROOT}/outputs", arcname="outputs")
    shutil.rmtree(ROOT, ignore_errors=True)
    print(f"packed {n} result records into {tgz} ({os.path.getsize(tgz) / 1e6:.1f} MB)",
          flush=True)


main()
