"""Track C gate 3: one shard of the 50-100 pc kill test on a Kaggle CPU session.

Generated by gate3/build3.py; the payload lines are filled in. Steps: report resources; unpack
the embedded `git archive` of the pinned commit; build the gate-2 Python 3.13 venv (uv, pins);
run gate3/kdriver3.py (fetch, noise, frozen search, frozen v2 vetting measurement) with a
deadline; delete the light curves; pack the result records into /kaggle/working/<tag>.tar.gz.
"""

import base64
import gzip
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile
import time

T0 = time.time()
CFG = json.loads(base64.b64decode("@@CFG@@").decode())
FILES = json.loads(gzip.decompress(base64.b64decode("@@FILES@@")).decode())
CODE_TGZ = "@@CODE@@"

W = "/kaggle/working"
ROOT = f"{W}/ow"
CODE = "/tmp/ow-code"
VENV = "/tmp/ow-venv"


def sh(cmd, **kw):
    print("$", " ".join(cmd), flush=True)
    return subprocess.run(cmd, check=True, **kw)


def main():
    du = shutil.disk_usage(W)
    print(f"resources: cpus {os.cpu_count()} {open('/proc/meminfo').readline().strip()} "
          f"free {du.free / 1e9:.1f} GB nonce {CFG['nonce']}", flush=True)
    os.makedirs(CODE, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(CODE_TGZ))) as t:
        t.extractall(CODE, filter="data")
    print(f"code: embedded git archive of {CFG['commit']}", flush=True)
    sh([sys.executable, "-m", "pip", "install", "--quiet", "--disable-pip-version-check",
        f"uv=={CFG['uv']}"])
    uv = [sys.executable, "-m", "uv"]
    sh(uv + ["venv", "--quiet", "--python", CFG["python"], VENV])
    py = f"{VENV}/bin/python"
    sh(uv + ["pip", "install", "--quiet", "--python", py] + CFG["pins"])
    for name, text in FILES.items():
        with open(f"/tmp/{name}", "w") as fh:
            fh.write(text)
    deadline = T0 + 3600 * CFG["search_hours"]
    env = dict(os.environ, ODDBALL_MAIN=ROOT, CUDA_VISIBLE_DEVICES="", PYTHONUNBUFFERED="1",
               NUMBA_NUM_THREADS="1", OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1",
               MKL_NUM_THREADS="1")
    os.makedirs(f"{ROOT}/outputs/planets_spike/gate3/run", exist_ok=True)
    with open(f"{ROOT}/outputs/planets_spike/gate3/run/driver.log", "a") as log:
        p = subprocess.Popen([py, "-I", f"{CODE}/spikes/mdwarf_stack/gate3/kdriver3.py",
                              "--sample", "/tmp/sample.csv", "--ref", "/tmp/ref.csv",
                              "--info", "/tmp/star_info.json", "--deadline", str(deadline),
                              "--vet-minutes", str(CFG["vet_minutes"])],
                             env=env, cwd=f"{CODE}/spikes/mdwarf_stack", stdout=subprocess.PIPE,
                             stderr=subprocess.STDOUT, text=True)
        for line in p.stdout:
            sys.stdout.write(line)
            log.write(line)
        rc = p.wait()
    shutil.rmtree(f"{ROOT}/data", ignore_errors=True)
    run = f"{ROOT}/outputs/planets_spike/gate3/run"
    for f in os.listdir(run):
        if f.endswith(".npz"):
            os.remove(f"{run}/{f}")
    summary = dict(CFG, driver_exit=rc, hours=(time.time() - T0) / 3600)
    with open(f"{run}/kaggle_summary.json", "w") as fh:
        json.dump(summary, fh)
    tgz = f"{W}/{CFG['tag']}.tar.gz"
    with tarfile.open(tgz, "w:gz") as t:
        t.add(run, arcname="run")
    shutil.rmtree(ROOT, ignore_errors=True)
    print(f"packed {tgz} ({os.path.getsize(tgz) / 1e6:.1f} MB) driver exit {rc}", flush=True)


main()
